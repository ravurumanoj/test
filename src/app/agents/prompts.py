# Mermaid syntax rules — the one part of formatting kept strictly mandatory (not a
# style default): the rendering surface has shown "Parsing failed" errors when the
# LLM emits arrows, unquoted symbols/currency, or non-pie diagram types. Shared by
# OUTPUT_FORMATTING_GUIDELINES (sub-agent prompts) and the orchestrator's system
# prompt (relationship_manager.py) so the rule lives in exactly one place. A backend
# sanitizer (RelationshipManagerOrchestrator._sanitize_mermaid_diagrams) also
# repairs/strips malformed blocks as a last-resort net, but the model must not rely
# on that — it must emit valid syntax the first time, whenever it uses a diagram.
MERMAID_PIE_RULES = (
    "Mermaid rules (STRICT whenever you choose to use one — invalid syntax breaks the UI):\n"
    "- ONLY the `pie` chart type. Never flowchart/graph/sequenceDiagram/gantt/other types, "
    "and never arrows (->, <-, -->, <-->) anywhere.\n"
    "- Exact shape, with a real filled example:\n"
    "  ```mermaid\n"
    "  pie title Asset Allocation\n"
    "      \"Equities\" : 42.5\n"
    "      \"Fixed Income\" : 31.0\n"
    "      \"Cash\" : 26.5\n"
    "  ```\n"
    "- Title: plain text only — no quotes, colons, arrows, angle brackets, backslashes, "
    "or backticks.\n"
    "- Each label must stay wrapped in double quotes. Inside the label use plain text only "
    "— no quotes, colons, arrows, angle brackets, backslashes, or backticks.\n"
    "- Values: a bare number (e.g. 42.5) — no currency symbols, '%', commas, or units.\n"
    "- Max 7 slices — merge the smallest real categories into a single \"Other\" slice when "
    "needed. Aggregating real values into \"Other\" is allowed; inventing values is not.\n"
    "- Nothing else inside the fence — no commentary, no blank filler lines.\n"
    "- Not fully certain it's valid? Skip the chart and use a table instead — a correct "
    "table beats a broken chart."
)

SHARED_PORTFOLIO_ANALYSIS_RULES = (
    "- Do not output wrapper labels such as 'Answer:' and do not repeat the same point in "
    "multiple phrasings.\n"
    "- For holdings, allocation, performance, or valuation tables, add concise commentary "
    "that explains the main takeaway, concentration, driver, or risk visible in the data.\n"
    "- 'Top contributors', 'top detractors', 'best performers', or 'worst performers' must "
    "be answered at instrument/holding level whenever holdings-level data is available. Do "
    "not substitute currency-level, asset-class-level, or whole-portfolio totals unless the "
    "user explicitly asked for those levels.\n"
    "- Holdings-level ranking data is available when retrieved records include fields such as "
    "unrealised_pct, pl_pct, market_value_usd, market_value_local, quantity, last_price, or "
    "instrument identifiers. Use those fields to rank and explain contributors/detractors; do "
    "not claim the ranking cannot be determined if those holdings-level fields are present.\n"
    "- Treat dates literally. Only mention a maturity date, valuation date, price date, event "
    "date, or any other date if that exact field is present for the relevant item. Never infer "
    "one date from another. If the user explicitly asked for a date that is not present, say it "
    "is not available in the retrieved data.\n"
)

# Shared formatting rules appended to every sub-agent summarisation prompt so each
# tool's summary is already well-structured before the orchestrator combines them.
# These are DEFAULT TOOLS, not a mandatory checklist — the retrieved JSON shape varies
# by tool/customer/data source, so the model must build structure from whatever fields
# are actually populated for this call, and may use a different clear format when it
# fits the specific data/question better.
OUTPUT_FORMATTING_GUIDELINES = (
    "Formatting (defaults to reach for, not a rigid checklist — use judgment based on "
    "the question and the data actually present; a different clear format is fine when "
    "it communicates better):\n"
    "- Return the answer directly. Never prefix sections or paragraphs with labels like "
    "'Answer:', 'Response:', 'Final Answer:', or repeat the same conclusion twice in "
    "different wording.\n"
    "- Say each fact once. If a table/chart already shows the numbers, add only brief "
    "interpretation around it instead of restating every row in prose.\n"
    "- Multi-item data (holdings, allocations, interactions, suggestions, metrics) → a "
    "GitHub-flavored markdown table with clear column headers is usually clearest. "
    "Never dump raw JSON or key:value pairs.\n"
    "- Tables should be readable and decision-oriented: order rows by importance where it "
    "helps, keep numeric precision consistent, and add a short lead-in or takeaway that "
    "explains what matters in the table.\n"
    "- A single proportional breakdown with 3+ categories (e.g. asset allocation, sector "
    "exposure, currency allocation) often benefits from a Mermaid PIE chart above the "
    "table — include one when it adds clarity, per the strict rules below.\n"
    "- When using a pie chart, make it feel modern through better information design: short "
    "labels, meaningful slice ordering, and a companion takeaway/table. Do not rely on the "
    "chart alone to carry the message.\n"
    "- Do not claim or imply that the prompt controls chart colors. The prompt controls only "
    "chart content and structure; visual theming may be applied separately by the renderer.\n"
    "- When values indicate gain/profit/upside vs loss/downside, make that obvious in the "
    "wording and table text using clear markers such as Gain/Loss, Positive/Negative, or "
    "up/down wording. Do not rely on color alone because markdown rendering may vary.\n"
    "- For portfolio or valuation questions, do not stop at raw numbers. Add 1-3 short "
    "sentences of commentary that explain the main drivers, concentrations, offsets, or "
    "notable absences visible in the retrieved data.\n"
    "- Bold key figures and time-sensitive items (overdue dates, alerts, compliance flags).\n"
    "- Only chart/tabulate values actually present in the retrieved data — never invent "
    "rows or slices, and skip a table/chart entirely when there isn't enough real data "
    "to justify one.\n\n"
    f"{MERMAID_PIE_RULES}"
)

